create table if not exists public.rsvps (
  id bigint generated by default as identity primary key,
  name text not null,
  attendance text not null check (attendance in ('Hadir','InsyaAllah hadir','Berhalangan')),
  guest_count int not null default 1 check (guest_count between 1 and 10),
  message text default '',
  created_at timestamptz not null default now()
);

alter table public.rsvps enable row level security;

-- Kebijakan demo: publik boleh mengirim RSVP dan admin membaca melalui key server.
-- Untuk produksi, gunakan autentikasi admin dan policy yang lebih ketat.
create policy "public can submit rsvp"
on public.rsvps for insert to anon, authenticated
with check (char_length(name) between 1 and 120);

create policy "authenticated can read rsvp"
on public.rsvps for select to authenticated
using (true);